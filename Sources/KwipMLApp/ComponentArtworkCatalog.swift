    static func assetName(for type:String)->String? {
        assets[type] ?? (type == "train" ? assets["workflow.train"] : type.hasPrefix("composite:") ? assets["kwip.block"]:nil)
    }
    private static let images:[String:NSImage] = {
        var result=[String:NSImage]()
        for name in Set(assets.values).union([checkpointLifecycleAssetName]) {
            if let url=Bundle.module.url(forResource:name,withExtension:"png")
                ?? Bundle.module.url(forResource:name,withExtension:"png",subdirectory:"ComponentIcons"),
                let image=NSImage(contentsOf:url) {result[name]=image}
        }
        return result
    }()
    static var checkpointLifecycleAssetName: String {
        URL(fileURLWithPath: BundledLifecycleCapabilities.entry.presentation.icon)
            .deletingPathExtension().lastPathComponent
    }
    static var checkpointLifecycleImage: NSImage? {
        images[checkpointLifecycleAssetName]
    }
    static func image(for type:String)->NSImage? {
        guard let name=assetName(for:type) else {return nil}
        return images[name]
    }
