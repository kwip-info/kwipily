import XCTest
import AppKit
@testable import KwipMLApp

@MainActor final class ApplicationNavigationWindowsTests: XCTestCase {
    func testApplicationSurfacesAreDistinctReusableAndNeverCanvasTabs() throws {
        _ = NSApplication.shared
        let storage = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: storage) }
        let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        let session = ProjectWindowSession(workspace: WorkspaceStore(rootOverride: root, storageOverride: storage, detectCapabilities: false))
        let navigation = ApplicationNavigationWindows(presentsWindows: false)
        navigation.configure(session: session)
        navigation.showSettings()
        let settings = try XCTUnwrap(navigation.settingsWindow)
        navigation.showSettings()
        XCTAssertTrue(navigation.settingsWindow === settings)
        navigation.settingsNavigation.search = "unrelated prior search"
        navigation.showSettings(page: .models)
        XCTAssertTrue(navigation.settingsWindow === settings, "A model prerequisite reuses Settings without discarding drafts")
        XCTAssertEqual(navigation.settingsNavigation.selected, .models)
        XCTAssertEqual(navigation.settingsNavigation.search, "", "Explicit model navigation must not be hidden by a prior search")
        navigation.settingsNavigation.search = "OCR"
        navigation.showSettings()
        XCTAssertEqual(navigation.settingsNavigation.selected, .models)
        XCTAssertEqual(navigation.settingsNavigation.search, "OCR", "Ordinary reopen preserves the user's Settings state")
        navigation.showLearn()
        let learn = try XCTUnwrap(navigation.learnWindow)
        XCTAssertFalse(settings === learn)
        XCTAssertEqual(settings.tabbingMode, .disallowed)
        XCTAssertEqual(learn.tabbingMode, .disallowed)
        XCTAssertNotEqual(settings.identifier, learn.identifier)
        XCTAssertEqual(session.workspace.activeSection, "Projects", "Global navigation must not replace welcome or a document surface")
        XCTAssertNil(session.workspace.activeProjectID, "Opening catalogs/settings must not fabricate a file")
        navigation.showLearn(search: DiagnosticAudienceGuide.lessonSearchTerm)
        XCTAssertTrue(navigation.learnWindow === learn, "A finding opens the existing library, not another window")
        XCTAssertEqual(navigation.learnNavigation.section, "Library")
        XCTAssertEqual(navigation.learnNavigation.search, "diagnostics")
        XCTAssertNil(session.workspace.activeProjectID, "Matching lesson navigation must not launch or replace a project")
        navigation.showTemplates(id:"document-ocr")
        let templates=try XCTUnwrap(navigation.templatesWindow)
        XCTAssertEqual(templates.tabbingMode,.disallowed)
        XCTAssertLessThanOrEqual(templates.contentLayoutRect.height,900)
        navigation.showTemplates(id:"rental-planning")
        XCTAssertTrue(navigation.templatesWindow === templates)
        XCTAssertEqual(navigation.templateNavigation.selectedID,"rental-planning")
        XCTAssertNil(session.workspace.activeProjectID,"Browsing templates must not create a project")
        templates.close()
        navigation.showTemplates()
        let reopenedTemplates=try XCTUnwrap(navigation.templatesWindow)
        XCTAssertFalse(reopenedTemplates === templates,"A closed expanded editor must get a fresh lifetime")
        XCTAssertEqual(navigation.templateNavigation.selectedID,"rental-planning")
        reopenedTemplates.close()
        navigation.showLearn()
        XCTAssertEqual(navigation.learnNavigation.search, "diagnostics", "Ordinary reopen preserves the reader's library state")
        let projectIDs = session.workspace.projects.map(\.id)
        let lessonProjectIDs = session.workspace.lessonProjects.map(\.id)
        navigation.showLearn(entryID: "affine")
        XCTAssertTrue(navigation.learnWindow === learn)
        XCTAssertEqual(navigation.learnNavigation.directEntryID, "affine")
        XCTAssertEqual(session.workspace.projects.map(\.id), projectIDs, "Reading must not create a lesson project")
        XCTAssertNil(session.workspace.activeProjectID)
        XCTAssertEqual(session.workspace.lessonProjects.map(\.id), lessonProjectIDs, "Reading must not create learning work or completion")
        navigation.showLearn(entryID: "not-a-lesson")
        XCTAssertEqual(navigation.learnNavigation.directEntryID, "affine")
        learn.close(); settings.close()
        navigation.showLearn()
        XCTAssertTrue(navigation.learnWindow === learn, "Closing and reopening retains one catalog and its learning state")
        learn.close()
    }
}
