#!/usr/bin/env python3
"""Generate deterministic, relative navigation without moving historical evidence."""
import argparse
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote

MARKER = '<!-- Generated by scripts/documentation_index.py; do not edit. -->'


def label(value):
    for character in ('\\', '|', '[', ']', '<', '>'):
        value = value.replace(character, '\\' + character)
    return value


def title(path):
    for line in path.read_text(encoding='utf-8').splitlines():
        if line.startswith('# '):
            return line[2:].strip()
    return path.stem


def outputs(root):
    docs = root / 'docs'
    sources = sorted((p for p in docs.rglob('*.md')
                      if p.name != 'INDEX.md' and not p.is_symlink()),
                     key=lambda p: p.as_posix().casefold())
    directories = {docs}
    for source in sources:
        directories.update(parent for parent in source.parents
                           if parent == docs or docs in parent.parents)
    result = {}
    for directory in sorted(directories):
        relative = directory.relative_to(root).as_posix()
        lines = [f'# {relative} — index', '', MARKER, '',
                 'Navigation only: dated evidence is historical unless a maintained contract or tracker adopts it.', '']
        if directory == docs:
            lines += ['[Repository](../README.md) · [Start here](README.md)', '']
        else:
            lines += ['[Parent index](../INDEX.md)', '']
        children = sorted((p for p in directories if p.parent == directory), key=lambda p: p.name.casefold())
        if children:
            lines += ['## Sections', '']
            for child in children:
                count = sum(child in source.parents for source in sources)
                lines.append(f'- [{label(child.name)}]({quote(child.name)}/INDEX.md) — {count} documents')
            lines.append('')
        groups = defaultdict(list)
        direct = [p for p in sources if p.parent == directory]
        for source in direct:
            group = source.stem.split('_')[0] if len(direct) > 40 and '_' in source.stem else 'Documents'
            groups[group].append(source)
        for group, members in sorted(groups.items()):
            lines += [f'## {label(group)}', '', '| Document | File |', '|---|---|']
            for source in members:
                lines.append(f'| [{label(title(source))}]({quote(source.name)}) | {label(source.name)} |')
            lines.append('')
        result[directory / 'INDEX.md'] = '\n'.join(lines).rstrip() + '\n'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check', action='store_true', help='Refuse drift without modifying files.')
    args = parser.parse_args()
    root = args.root.resolve()
    if not (root / 'docs').is_dir():
        parser.error('root must contain docs/')
    expected = outputs(root)
    stale = [p for p, content in expected.items() if not p.exists() or p.read_text(encoding='utf-8') != content]
    obsolete = [p for p in (root / 'docs').rglob('INDEX.md')
                if p not in expected and MARKER in p.read_text(encoding='utf-8')]
    if args.check:
        for path in stale + obsolete:
            print(f'Index drift: {path.relative_to(root)}')
        print(f'{len(expected)} indexes checked; {len(stale) + len(obsolete)} differences.')
        return int(bool(stale or obsolete))
    for path in stale:
        if path.exists() and MARKER not in path.read_text(encoding='utf-8'):
            parser.error(f'Refusing to overwrite an authored index: {path}')
    for path in stale:
        path.write_text(expected[path], encoding='utf-8')
    for path in obsolete:
        path.unlink()
    print(f'{len(expected)} indexes generated; {len(stale)} updated; {len(obsolete)} obsolete removed.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
